// Service worker voor de taken-app: maakt hem installeerbaar en laat de laatst geladen
// pagina's zien als je even geen verbinding hebt. De API wordt nooit gecachet.
// Pushmeldingen komen hier later bij.

const CACHE = "taken-v1";

self.addEventListener("install", () => self.skipWaiting());

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const { request } = event;
  const url = new URL(request.url);
  if (request.method !== "GET" || url.origin !== self.location.origin || url.pathname.startsWith("/api/")) return;

  // Next.js-bestanden hebben een hash in de naam: eerst uit de cache.
  if (url.pathname.startsWith("/_next/static/") || url.pathname.startsWith("/taken-pwa/")) {
    event.respondWith(
      caches.match(request).then(
        (hit) =>
          hit ||
          fetch(request).then((res) => {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(request, copy));
            return res;
          })
      )
    );
    return;
  }

  // Pagina's: eerst het netwerk, zonder verbinding de laatst bekende versie.
  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request)
        .then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(request, copy));
          }
          return res;
        })
        .catch(() => caches.match(request).then((hit) => hit || caches.match("/taken")))
    );
  }
});
